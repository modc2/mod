"""Generate eth/src/PoseidonRC.sol: Starknet Poseidon round constants as a
Solidity function that fills a memory array (the permutation loop in
Poseidon.sol reads them from memory).

    python3 tools/gen_eth_consts.py

Source: lambdaworks-crypto 0.13 `OPTIMIZED_ROUND_CONSTANTS` (107 felts), the
same table near/src/poseidon.rs is generated from (tools/gen_fp.py), checked
against the Cairo fixture (near/tests/fixture.json key ids) before writing.
"""
import glob
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
P = 2 ** 251 + 17 * 2 ** 192 + 1
src = sorted(glob.glob(os.path.expanduser(
    '~/.cargo/registry/src/*/lambdaworks-crypto-0.13.0/src/hash/poseidon/'
    'starknet/parameters.rs')))[0]
params = open(src).read()
i = params.index('const OPTIMIZED_ROUND_CONSTANTS')
RC = [int(h, 16) for h in re.findall(
    r'from_hex_unchecked\(\s*"([0-9a-fA-F]+)"', params[i:params.index('];', i)])]
assert len(RC) == 107


def hades(s):
    k = 0
    def mix():
        t = sum(s) % P
        s[0], s[1], s[2] = (t + 2 * s[0]) % P, (t - 2 * s[1]) % P, (t - 3 * s[2]) % P
    for _ in range(4):
        for j in range(3):
            s[j] = pow((s[j] + RC[k + j]) % P, 3, P)
        mix()
        k += 3
    for _ in range(83):
        s[2] = pow((s[2] + RC[k]) % P, 3, P)
        mix()
        k += 1
    for _ in range(4):
        for j in range(3):
            s[j] = pow((s[j] + RC[k + j]) % P, 3, P)
        mix()
        k += 3


def hash_many(xs):
    v = list(xs) + [1]
    if len(v) % 2:
        v.append(0)
    s = [0, 0, 0]
    for a in range(0, len(v), 2):
        s[0] = (s[0] + v[a]) % P
        s[1] = (s[1] + v[a + 1]) % P
        hades(s)
    return s[0]


def short(t):
    return int.from_bytes(t.encode(), 'big')


if __name__ == '__main__':
    fx = json.load(open(os.path.join(HERE, '..', 'near', 'tests', 'fixture.json')))
    for k in fx['keys']:
        assert hash_many([short('zuma-key'), int(k['x'], 16), int(k['y'], 16)]) == int(k['key_id'], 16)
    out = ['// SPDX-License-Identifier: MIT', 'pragma solidity ^0.8.24;', '',
           "/// @notice Round constants of Starknet's Poseidon (Hades permutation,",
           '/// width 3, 4 + 83 + 4 rounds, optimized partial-round constants).',
           '/// GENERATED by tools/gen_eth_consts.py from lambdaworks-crypto 0.13,',
           '/// the same table near/src/poseidon.rs is generated from.',
           'library PoseidonRC {',
           '    function load() internal pure returns (uint256[107] memory r) {']
    for n, c in enumerate(RC):
        out.append(f'        r[{n}] = 0x{c:064x};')
    out += ['    }', '}', '']
    path = os.path.join(HERE, '..', 'eth', 'src', 'PoseidonRC.sol')
    open(path, 'w').write('\n'.join(out))
    print('wrote', path)
