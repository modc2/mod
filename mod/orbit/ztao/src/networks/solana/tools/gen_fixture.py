"""Write contract/tests/hints.json: the Cairo-made fixture signature
(near/tests/fixture.json) plus every hint stark.py derives for it, so the
Rust unit tests of the Solana verifier run on real Cairo output.

    python3 src/networks/solana/tools/gen_fixture.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..', '..', 'core'))
import stark  # noqa: E402

fx = json.load(open(os.path.join(HERE, '..', '..', 'near', 'contract', 'tests', 'fixture.json')))
I = lambda v: int(v, 16) if isinstance(v, str) else int(v)
sg = fx['sig']
ring = [(I(p['x']), I(p['y'])) for p in sg['ring']]
scope, msg = I(fx['scope_mine']['scope']), I(fx['msg'])
image = (I(sg['image']['x']), I(sg['image']['y']))
s = [I(x) for x in sg['s']]
tr = stark.trace(ring, scope, msg, I(sg['c0']), s, image)
h = lambda v: f'0x{v:064x}'
p = lambda q: [h(0), h(0)] if q is None else [h(q[0]), h(q[1])]
out = {'note': 'GENERATED by solana/tools/gen_fixture.py',
       'ring': [p(q) for q in ring], 'scope': h(scope), 'msg': h(msg),
       'c0': h(I(sg['c0'])), 's': [h(x) for x in s], 'image': p(image),
       'tag': h(stark.key_id(image)),
       'hp': p(tr['hp']), 'hp_ctr': tr['hp_ctr'], 'd': h(tr['d']),
       'sponge': [[h(v) for v in st] for st in tr['sponge']],
       'c': [h(x) for x in tr['c']], 'L': [p(q) for q in tr['L']],
       'R': [p(q) for q in tr['R']],
       'mids': [[[p(q) for q in w] for w in m] for m in tr['mids']]}
# scopes whose Hp needs skipped counters (the non-square path)
cases = []
for sc in range(1, 64):
    hp, ctr = stark.hash_to_point(sc)
    if ctr >= 2:
        cases.append({'scope': h(sc), 'hp': p(hp), 'ctr': ctr})
    if len(cases) == 3:
        break
out['hp_cases'] = cases
path = os.path.join(HERE, '..', 'contract', 'tests', 'hints.json')
json.dump(out, open(path, 'w'), indent=1)
print('wrote', path, 'hp_ctr', tr['hp_ctr'])
