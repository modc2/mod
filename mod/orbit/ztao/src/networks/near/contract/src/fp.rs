        let mut t12: u64 = mu(a[4], b[8]).wrapping_add(mu(a[5], b[7])).wrapping_add(mu(a[6], b[6])).wrapping_add(mu(a[7], b[5])).wrapping_add(mu(a[8], b[4]));
        let mut t13: u64 = mu(a[5], b[8]).wrapping_add(mu(a[6], b[7])).wrapping_add(mu(a[7], b[6])).wrapping_add(mu(a[8], b[5]));
        let mut t14: u64 = mu(a[6], b[8]).wrapping_add(mu(a[7], b[7])).wrapping_add(mu(a[8], b[6]));
        let mut t15: u64 = mu(a[7], b[8]).wrapping_add(mu(a[8], b[7]));
        let mut t16: u64 = mu(a[8], b[8]);
