        t16 = t16.wrapping_add(t15 >> 29); t15 &= MASK;
        t17 = t17.wrapping_add(t16 >> 29); t16 &= MASK;
        let mut r = [t9, t10, t11, t12, t13, t14, t15, t16, t17];
        if geq_p(&r) {
            sub_p(&mut r);
        }
        Fp(r)
