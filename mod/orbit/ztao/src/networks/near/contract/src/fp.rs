        t10 = t10.wrapping_add(m << 19);
        m = t3.wrapping_neg() & MASK;
        t4 = t4.wrapping_add(t3.wrapping_add(m) >> 29);
        t9 = t9.wrapping_add(mu(m, 17 << 18));
        t11 = t11.wrapping_add(m << 19);
        m = t4.wrapping_neg() & MASK;
        t5 = t5.wrapping_add(t4.wrapping_add(m) >> 29);
        t10 = t10.wrapping_add(mu(m, 17 << 18));
        t12 = t12.wrapping_add(m << 19);
        m = t5.wrapping_neg() & MASK;
        t6 = t6.wrapping_add(t5.wrapping_add(m) >> 29);
        t11 = t11.wrapping_add(mu(m, 17 << 18));
        t13 = t13.wrapping_add(m << 19);
        m = t6.wrapping_neg() & MASK;
        t7 = t7.wrapping_add(t6.wrapping_add(m) >> 29);
        t12 = t12.wrapping_add(mu(m, 17 << 18));
        t14 = t14.wrapping_add(m << 19);
        m = t7.wrapping_neg() & MASK;
        t8 = t8.wrapping_add(t7.wrapping_add(m) >> 29);
        t13 = t13.wrapping_add(mu(m, 17 << 18));
        t15 = t15.wrapping_add(m << 19);
        m = t8.wrapping_neg() & MASK;
        t9 = t9.wrapping_add(t8.wrapping_add(m) >> 29);
        t14 = t14.wrapping_add(mu(m, 17 << 18));
        t16 = t16.wrapping_add(m << 19);
        t10 = t10.wrapping_add(t9 >> 29); t9 &= MASK;
        t11 = t11.wrapping_add(t10 >> 29); t10 &= MASK;
        t12 = t12.wrapping_add(t11 >> 29); t11 &= MASK;
