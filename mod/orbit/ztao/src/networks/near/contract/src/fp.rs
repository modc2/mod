        let mut t10: u64 = mu(a[2], b[8]).wrapping_add(mu(a[3], b[7])).wrapping_add(mu(a[4], b[6])).wrapping_add(mu(a[5], b[5])).wrapping_add(mu(a[6], b[4])).wrapping_add(mu(a[7], b[3])).wrapping_add(mu(a[8], b[2]));
