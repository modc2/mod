        let mut t4: u64 = mu(a[0], b[4]).wrapping_add(mu(a[1], b[3])).wrapping_add(mu(a[2], b[2])).wrapping_add(mu(a[3], b[1])).wrapping_add(mu(a[4], b[0]));
        let mut t5: u64 = mu(a[0], b[5]).wrapping_add(mu(a[1], b[4])).wrapping_add(mu(a[2], b[3])).wrapping_add(mu(a[3], b[2])).wrapping_add(mu(a[4], b[1])).wrapping_add(mu(a[5], b[0]));
        let mut t6: u64 = mu(a[0], b[6]).wrapping_add(mu(a[1], b[5])).wrapping_add(mu(a[2], b[4])).wrapping_add(mu(a[3], b[3])).wrapping_add(mu(a[4], b[2])).wrapping_add(mu(a[5], b[1])).wrapping_add(mu(a[6], b[0]));
        let mut t7: u64 = mu(a[0], b[7]).wrapping_add(mu(a[1], b[6])).wrapping_add(mu(a[2], b[5])).wrapping_add(mu(a[3], b[4])).wrapping_add(mu(a[4], b[3])).wrapping_add(mu(a[5], b[2])).wrapping_add(mu(a[6], b[1])).wrapping_add(mu(a[7], b[0]));
