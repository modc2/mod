        let mut m: u64;
        m = t0.wrapping_neg() & MASK;
        t1 = t1.wrapping_add(t0.wrapping_add(m) >> 29);
        t6 = t6.wrapping_add(mu(m, 17 << 18));
        t8 = t8.wrapping_add(m << 19);
        m = t1.wrapping_neg() & MASK;
        t2 = t2.wrapping_add(t1.wrapping_add(m) >> 29);
        t7 = t7.wrapping_add(mu(m, 17 << 18));
        t9 = t9.wrapping_add(m << 19);
        m = t2.wrapping_neg() & MASK;
        t3 = t3.wrapping_add(t2.wrapping_add(m) >> 29);
