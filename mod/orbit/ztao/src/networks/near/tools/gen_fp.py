"""Generate the field core of near/contract/src/fp.rs (between the GENERATED markers).

    python3 src/networks/near/tools/gen_fp.py  # rewrites contract/src/fp.rs in place

Radix 2^29, 9 limbs (261 bits), Montgomery R = 2^261, values kept fully
reduced (< p) with every limb < 2^29 between operations.

Why radix 29: a 29x29-bit product is < 2^58, so a column of 9 products is
< 2^62 and the schoolbook accumulates with NO carry handling at all; only the
final 18 columns are normalized. In wasm that roughly halves the op count of a
32-bit-limb multiply (whose every step must split a 64-bit sum).

Reduction uses p's shape. In radix 2^29:
    p = 1 + (17 << 18) * 2^(29*6) + (1 << 19) * 2^(29*8)
and p = 1 mod 2^29, so the Montgomery factor is m = -t_i mod 2^29 and m*p is
three shifted adds — no multiplies by p at all.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
FP = os.path.join(HERE, '..', 'contract', 'src', 'fp.rs')
N, W = 9, 29
MASK = (1 << W) - 1
p = 2 ** 251 + 17 * 2 ** 192 + 1
R = 2 ** (N * W)


def limbs(v):
    return [(v >> (W * i)) & MASK for i in range(N)]


assert limbs(p) == [1, 0, 0, 0, 0, 0, 17 << 18, 0, 1 << 19]
L = []
w = L.append


def arr(v):
    return '[' + ', '.join(f'0x{x:08x}' for x in limbs(v)) + ']'


def ad(terms):
    if not terms:
        return '0'
    e = terms[0]
    for t in terms[1:]:
        e = f'{e}.wrapping_add({t})'
    return e


def reduce_and_finish():
    # t0..t17 hold column sums (< 2^63). 9 lazy Montgomery rounds.
    w('        let mut m: u64;')
    for i in range(N):
        w(f'        m = t{i}.wrapping_neg() & MASK;')
        w(f'        t{i + 1} = t{i + 1}.wrapping_add(t{i}.wrapping_add(m) >> 29);')
        w(f'        t{i + 6} = t{i + 6}.wrapping_add(mu(m, 17 << 18));')
        w(f'        t{i + 8} = t{i + 8}.wrapping_add(m << 19);')
    # normalize t9..t17 into 9 limbs
    for k in range(N, 2 * N - 1):
        w(f'        t{k + 1} = t{k + 1}.wrapping_add(t{k} >> 29); t{k} &= MASK;')
    w('        let mut r = [' + ', '.join(f't{k}' for k in range(N, 2 * N)) + '];')
    w('        if geq_p(&r) {')
    w('            sub_p(&mut r);')
    w('        }')
    w('        Fp(r)')


def mul():
    w('    /// a*b/R. 81 products summed per column without carries, then')
    w('    /// 9 multiply-free reduction rounds.')
    w('    #[inline(never)]')
    w('    pub fn mul(&self, b: &Fp) -> Fp {')
    w('        let (a, b) = (&self.0, &b.0);')
    for k in range(2 * N):
        terms = [f'mu(a[{i}], b[{k - i}])' for i in range(N) if 0 <= k - i < N]
        w(f'        let {"mut " if k else ""}t{k}: u64 = ' + ad(terms) + ';')
    reduce_and_finish()
    w('    }')
    w('')


def sq():
    w('    /// a^2/R: 36 doubled cross products + 9 squares (45 vs 81).')
    w('    #[inline(never)]')
    w('    pub fn sq(&self) -> Fp {')
    w('        let a = &self.0;')
    for i in range(N - 1):
        w(f'        let d{i} = a[{i}] << 1;')
    for k in range(2 * N):
        terms = []
        for i in range(N):
            j = k - i
            if i < j < N:
                terms.append(f'mu(d{i}, a[{j}])')
            elif i == j:
                terms.append(f'mu(a[{i}], a[{i}])')
        w(f'        let {"mut " if k else ""}t{k}: u64 = ' + ad(terms) + ';')
    reduce_and_finish()
    w('    }')
    w('')


w('// ---- GENERATED by tools/gen_fp.py: do not edit by hand ----')
w(f'const MASK: u64 = 0x{MASK:x};')
w(f'const P: [u64; 9] = {arr(p)};')
w(f'/// R^2 mod p, R = 2^261 (into Montgomery form)')
w(f'const R2: [u64; 9] = {arr(R * R % p)};')
w(f'/// R mod p (Montgomery one)')
w(f'const R1: [u64; 9] = {arr(R % p)};')
w('')
w('/// A field element in Montgomery form: 9 limbs of 29 bits, fully reduced.')
w('#[derive(Clone, Copy, Debug, PartialEq, Eq)]')
w('pub struct Fp([u64; 9]);')
w('')
w('/// Wrapping multiply: the crate builds with overflow-checks, which would')
w('/// turn every checked u64 multiply into a 128-bit `__multi3` call in wasm.')
w('/// Every product here is < 2^59 by construction (29-bit limbs).')
w('#[inline(always)]')
w('fn mu(a: u64, b: u64) -> u64 {')
w('    a.wrapping_mul(b)')
w('}')
w('')
w('#[inline(always)]')
w('fn geq_p(a: &[u64; 9]) -> bool {')
w('    for i in (0..9).rev() {')
w('        if a[i] != P[i] {')
w('            return a[i] > P[i];')
w('        }')
w('    }')
w('    true')
w('}')
w('')
w('#[inline(always)]')
w('fn sub_p(a: &mut [u64; 9]) {')
w('    let mut borrow = 0i64;')
w('    for i in 0..9 {')
w('        let d = (a[i] as i64).wrapping_sub(P[i] as i64).wrapping_add(borrow);')
w('        a[i] = (d as u64) & MASK;')
w('        borrow = d >> 29;')
w('    }')
w('}')
w('')
w('impl Fp {')
w('    pub const ZERO: Fp = Fp([0; 9]);')
w('    pub const ONE: Fp = Fp(R1);')
w('')
mul()
sq()
w('    #[inline(always)]')
w('    pub fn add(&self, b: &Fp) -> Fp {')
w('        let mut r = [0u64; 9];')
w('        let mut c = 0u64;')
w('        for i in 0..9 {')
w('            let s = self.0[i].wrapping_add(b.0[i]).wrapping_add(c);')
w('            r[i] = s & MASK;')
w('            c = s >> 29;')
w('        }')
w('        if geq_p(&r) {')
w('            sub_p(&mut r);')
w('        }')
w('        Fp(r)')
w('    }')
w('')
w('    #[inline(always)]')
w('    pub fn sub(&self, b: &Fp) -> Fp {')
w('        let mut r = [0u64; 9];')
w('        let mut borrow = 0i64;')
w('        for i in 0..9 {')
w('            let d = (self.0[i] as i64).wrapping_sub(b.0[i] as i64).wrapping_add(borrow);')
w('            r[i] = (d as u64) & MASK;')
w('            borrow = d >> 29;')
w('        }')
w('        if borrow != 0 {')
w('            let mut c = 0u64;')
w('            for i in 0..9 {')
w('                let s = r[i].wrapping_add(P[i]).wrapping_add(c);')
w('                r[i] = s & MASK;')
w('                c = s >> 29;')
w('            }')
w('        }')
w('        Fp(r)')
w('    }')
w('')
w('    #[inline(always)]')
w('    pub fn dbl(&self) -> Fp {')
w('        self.add(self)')
w('    }')
w('')
w('    pub const fn from_limbs(l: [u64; 9]) -> Fp {')
w('        Fp(l)')
w('    }')
w('')
w('    pub fn is_zero(&self) -> bool {')
w('        self.0 == [0; 9]')
w('    }')
w('')
w('    pub fn from_felt(f: &Felt) -> Fp {')
w('        let b = f.to_bytes_be();')
w('        let mut l = [0u64; 9];')
w('        for (k, byte) in b.iter().rev().enumerate() {')
w('            let bit = 8 * k;')
w('            l[bit / 29] |= ((*byte as u64) << (bit % 29)) & MASK;')
w('            if bit % 29 > 21 && bit / 29 + 1 < 9 {')
w('                l[bit / 29 + 1] |= (*byte as u64) >> (29 - bit % 29);')
w('            }')
w('        }')
w('        Fp(l).mul(&Fp(R2))')
w('    }')
w('')
w('    pub fn to_felt(&self) -> Felt {')
w('        let mut one = [0u64; 9];')
w('        one[0] = 1;')
w('        let l = self.mul(&Fp(one)).0;')
w('        let mut b = [0u8; 32];')
w('        for k in 0..32 {')
w('            let bit = 8 * k;')
w('            let mut v = l[bit / 29] >> (bit % 29);')
w('            if bit % 29 > 21 && bit / 29 + 1 < 9 {')
w('                v |= l[bit / 29 + 1] << (29 - bit % 29);')
w('            }')
w('            b[31 - k] = v as u8;')
w('        }')
w('        Felt::from_bytes_be(&b)')
w('    }')
w('// ---- END GENERATED ----')

src = open(FP).read()
start = src.index('// ---- GENERATED') if '// ---- GENERATED' in src else None
if start is None:
    # first run: replace from `const P:` through the end of to_felt()
    start = src.index('const P: [u32; 8]')
    end = src.index('    /// Inverse via lambdaworks')
    body = '\n'.join(L).replace('// ---- END GENERATED ----', '')
    # keep `impl Fp {` open: inv/dbl follow in the hand-written part
    out = src[:start] + '\n'.join(L) + '\n' + src[end:]
else:
    end = src.index('// ---- END GENERATED ----') + len('// ---- END GENERATED ----')
    out = src[:start] + '\n'.join(L) + src[end:]
open(FP, 'w').write(out)
print('wrote', FP)


# ---- Poseidon (Starknet Hades, optimized round constants) -> poseidon.rs ----
import glob

src_glob = os.path.expanduser('~/.cargo/registry/src/*/lambdaworks-crypto-0.13.0/'
                              'src/hash/poseidon/starknet/parameters.rs')
params = open(sorted(glob.glob(src_glob))[0]).read()
i = params.index('const OPTIMIZED_ROUND_CONSTANTS')
consts = [int(h, 16) for h in re.findall(
    r'from_hex_unchecked\(\s*"([0-9a-fA-F]+)"', params[i:params.index('];', i)])]
assert len(consts) == 107
PO = os.path.join(HERE, '..', 'contract', 'src', 'poseidon.rs')
out = ['''//! Poseidon (Starknet's Hades permutation, Cairo `poseidon_hash_span`) on
//! the fast field. GENERATED by tools/gen_fp.py from lambdaworks-crypto's
//! optimized round constants (already in Montgomery form, R = 2^261).
//! lambdaworks remains the reference: tests/`poseidon_matches_reference`.
//! ~3x cheaper on NEAR than starknet_types_core::hash::Poseidon.
use crate::fp::Fp;
use starknet_types_core::felt::Felt;

#[rustfmt::skip]
const RC: [Fp; 107] = [''']
for c in consts:
    out.append('    Fp::from_limbs(' + arr(c * R % p) + '),')
out.append('''];

#[inline(always)]
fn cube(x: &Fp) -> Fp {
    x.sq().mul(x)
}

#[inline(always)]
fn mix(s: &mut [Fp; 3]) {
    let t = s[0].add(&s[1]).add(&s[2]);
    s[0] = t.add(&s[0].dbl());
    s[1] = t.sub(&s[1].dbl());
    s[2] = t.sub(&s[2].dbl().add(&s[2]));
}

pub fn hades(s: &mut [Fp; 3]) {
    let mut k = 0;
    for _ in 0..4 {
        for i in 0..3 {
            s[i] = cube(&s[i].add(&RC[k + i]));
        }
        mix(s);
        k += 3;
    }
    for _ in 0..83 {
        s[2] = cube(&s[2].add(&RC[k]));
        mix(s);
        k += 1;
    }
    for _ in 0..4 {
        for i in 0..3 {
            s[i] = cube(&s[i].add(&RC[k + i]));
        }
        mix(s);
        k += 3;
    }
}

/// poseidon_hash_span: rate 2, pad with 1 then 0s.
pub fn hash_many(inputs: &[Felt]) -> Felt {
    let mut v: Vec<Fp> = inputs.iter().map(Fp::from_felt).collect();
    v.push(Fp::ONE);
    if v.len() % 2 == 1 {
        v.push(Fp::ZERO);
    }
    let mut s = [Fp::ZERO; 3];
    for pair in v.chunks(2) {
        s[0] = s[0].add(&pair[0]);
        s[1] = s[1].add(&pair[1]);
        hades(&mut s);
    }
    s[0].to_felt()
}
''')
open(PO, 'w').write('\n'.join(out))
print('wrote', PO)
