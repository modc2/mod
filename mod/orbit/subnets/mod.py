import json
import os
import re
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from base import bt_call  # noqa: E402

ORBIT = os.path.dirname(HERE)
STATE = os.path.expanduser(os.environ.get('SUBNETS_STATE', '~/.mod/subnets'))
LOCK = os.path.join(STATE, 'sync.lock')
LOG = '/tmp/subnets-daily.log'
CRON_TAG = '# subnets daily mod sync'
CRON_SCHEDULE = os.environ.get('SUBNETS_CRON', '41 5 * * *')   # 05:41 UTC, after bt's day roll
GENERATED = '# GENERATED by orbit/subnets'
NEWS_PER_MOD = 8


def _now():
    return int(time.time())


def _day(ts):
    return time.strftime('%Y-%m-%d', time.gmtime(ts))


def _write(path, text):
    """Atomic write; returns True when the file actually changed."""
    try:
        with open(path) as f:
            if f.read() == text:
                return False
    except OSError:
        pass
    tmp = f'{path}.tmp{os.getpid()}'
    with open(tmp, 'w') as f:
        f.write(text)
    os.replace(tmp, path)
    return True


def _read_json(path, default=None):
    try:
        with open(path) as f:
            return json.load(f)
    except (OSError, json.JSONDecodeError):
        return default


def _dumps(obj):
    return json.dumps(obj, indent=2, ensure_ascii=False, sort_keys=False) + '\n'


def _strip_volatile(obj):
    """Compare snapshots without the timestamps that change every run."""
    if isinstance(obj, dict):
        return {k: _strip_volatile(v) for k, v in obj.items() if k not in ('updated', 'updated_day', 'block')}
    return obj


def _num(x, digits=4):
    if x is None:
        return '—'
    if abs(x) >= 1000:
        return f'{x:,.0f}'
    return f'{x:,.{digits}f}'


def _pct(x):
    return '—' if x is None else f'{x:+.2f}%'


def _md(s):
    return (s or '').replace('|', '\\|').replace('\n', ' ').strip()


def related_mods(rows, orbit=ORBIT):
    """Hand-built fleet mods that cover a subnet: a `netuid` field in their
    config.json, or an orbit dir named exactly like the subnet (chutes, targon…)."""
    names = {}
    for r in rows:
        key = re.sub(r'[^a-z0-9]', '', (r.get('name') or '').lower().split('.')[0])
        if len(key) >= 4:
            names.setdefault(key, r['netuid'])
    out = {}
    for d in sorted(os.listdir(orbit)):
        if d == 'subnets':
            continue
        cfg = _read_json(os.path.join(orbit, d, 'config.json'))
        if not isinstance(cfg, dict):
            continue
        n = cfg.get('netuid')
        if isinstance(n, int):
            out.setdefault(n, []).append(d)
        elif d in names:
            out.setdefault(names[d], []).append(d)
    return {k: sorted(set(v)) for k, v in out.items()}


