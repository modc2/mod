"""subnets — one mod per Bittensor subnet, regenerated once a day.

`sync()` reads the local orbit/bt index (screener + news + trade tape — no
third-party API, no keys) and writes, for every live netuid:

    subnets/sn<N>/config.json   identity, links, market numbers, related mods
    subnets/sn<N>/README.md     human page: what it is, market, 24h flow, news
    subnets/sn<N>/data.json     the full daily snapshot (what the mod serves offline)
    subnets/sn<N>/mod.py        a 10-line shim over base.Subnet — written ONCE;
                                if you replace it (drop the GENERATED marker) it
                                is never overwritten again.

Netuids that disappear are kept and marked `active: false`; a re-registered
netuid (new owner) records the old identity under `previous`. Every write is
atomic and skipped when nothing changed apart from the timestamp.

CLI (what the cron runs):  python3 mod.py sync | status | install_cron | uninstall_cron
"""

